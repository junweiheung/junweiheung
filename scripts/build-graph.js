#!/usr/bin/env node
/*
 * Builds js/graph-data.js for the connections map (the Map view of html/all.html) from js/articles.js and the explainer pages.
 * Three kinds of connection between two explainers:
 *   link     — one page links to the other in its text (found by scanning html/explainers/*.html)
 *   company  — both list the same company in their `chain` (articles.js)
 *   related  — a hand-picked pair in `related` (articles.js), with a one-line reason
 * Run by scripts/build-feed.js; can also be run on its own:  node scripts/build-graph.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
global.window = global.window || {};
delete require.cache[path.join(ROOT, "js", "articles.js")];
require(path.join(ROOT, "js", "articles.js"));
const { articles, companies = {}, related = [] } = window.BOTTLENECK;

const ids = new Set(articles.map((a) => a.id));
const byFile = Object.fromEntries(articles.map((a) => [path.basename(a.href, ".html"), a.id]));
const edges = new Map();
const key = (a, b) => (a < b ? a + "|" + b : b + "|" + a);
const edge = (a, b) => {
  const k = key(a, b);
  if (!edges.has(k)) { const [x, y] = k.split("|"); edges.set(k, { a: x, b: y, link: [], companies: [], related: "" }); }
  return edges.get(k);
};

// 1. links written in the text
articles.forEach((art) => {
  const file = path.join(ROOT, "html", art.href);
  if (!fs.existsSync(file)) return;
  const html = fs.readFileSync(file, "utf8");
  const seen = new Set();
  for (const m of html.matchAll(/href="(?:\.\.\/explainers\/|\.\/)?([a-z0-9-]+)\.html(?:#[^"]*)?"/g)) {
    const to = byFile[m[1]];
    if (!to || to === art.id || seen.has(to)) continue;
    seen.add(to);
    const e = edge(art.id, to);
    if (!e.link.includes(art.id)) e.link.push(art.id);           // who links out (direction)
  }
});

// 2. shared companies
const coSets = articles.map((a) => [a.id, new Set((a.chain || []).flatMap((s) => s.companies))]);
for (let i = 0; i < coSets.length; i++) for (let j = i + 1; j < coSets.length; j++) {
  const shared = [...coSets[i][1]].filter((c) => coSets[j][1].has(c));
  if (shared.length) edge(coSets[i][0], coSets[j][0]).companies = shared.map((c) => (companies[c] && companies[c].name) || c);
}

// 3. hand-picked related topics
related.forEach(([a, b, why]) => {
  if (!ids.has(a) || !ids.has(b)) { console.warn(`warning: related pair ${a}–${b} names an unknown explainer`); return; }
  edge(a, b).related = why;
});

const out = [...edges.values()].sort((x, y) => (x.a + x.b).localeCompare(y.a + y.b));
const js = `/* Generated by scripts/build-graph.js from js/articles.js and html/explainers/*.html. Do not edit by hand. */
window.BOTTLENECK_GRAPH = ${JSON.stringify({ edges: out })};
`;
fs.writeFileSync(path.join(ROOT, "js", "graph-data.js"), js);
const n = (f) => out.filter(f).length;
console.log(`js/graph-data.js written: ${out.length} connection(s) — ${n((e) => e.link.length)} text link, ${n((e) => e.companies.length)} shared company, ${n((e) => e.related)} related`);
